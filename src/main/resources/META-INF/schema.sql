DROP TABLE IF EXISTS vet_specialties;
DROP TABLE IF EXISTS visits;
DROP TABLE IF EXISTS ducks;
DROP TABLE IF EXISTS duck_types;
DROP TABLE IF EXISTS owners;
DROP TABLE IF EXISTS specialties;
DROP TABLE IF EXISTS vets;
DROP SEQUENCE IF EXISTS owner_seq;
DROP SEQUENCE IF EXISTS duck_type_seq;
DROP SEQUENCE IF EXISTS duck_seq;
DROP SEQUENCE IF EXISTS visit_seq;
DROP SEQUENCE IF EXISTS vet_seq;
DROP SEQUENCE IF EXISTS specialty_seq;
CREATE SEQUENCE owner_seq START 1 INCREMENT 1;
CREATE SEQUENCE duck_type_seq START 1 INCREMENT 1;
CREATE SEQUENCE duck_seq START 1 INCREMENT 1;
CREATE SEQUENCE visit_seq START 1 INCREMENT 1;
CREATE SEQUENCE vet_seq START 1 INCREMENT 1;
CREATE SEQUENCE specialty_seq START 1 INCREMENT 1;
CREATE TABLE owners (id BIGINT PRIMARY KEY DEFAULT nextval('owner_seq'), first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL, address VARCHAR(255) NOT NULL, city VARCHAR(100) NOT NULL, telephone VARCHAR(20) NOT NULL);
CREATE TABLE duck_types (id BIGINT PRIMARY KEY DEFAULT nextval('duck_type_seq'), name VARCHAR(80) NOT NULL);
CREATE TABLE ducks (id BIGINT PRIMARY KEY DEFAULT nextval('duck_seq'), name VARCHAR(100) NOT NULL, birth_date DATE NOT NULL, type_id BIGINT NOT NULL REFERENCES duck_types(id), owner_id BIGINT NOT NULL REFERENCES owners(id));
CREATE TABLE visits (id BIGINT PRIMARY KEY DEFAULT nextval('visit_seq'), visit_date DATE NOT NULL, description VARCHAR(1024) NOT NULL, duck_id BIGINT NOT NULL REFERENCES ducks(id));
CREATE TABLE vets (id BIGINT PRIMARY KEY DEFAULT nextval('vet_seq'), first_name VARCHAR(100) NOT NULL, last_name VARCHAR(100) NOT NULL);
CREATE TABLE specialties (id BIGINT PRIMARY KEY DEFAULT nextval('specialty_seq'), name VARCHAR(80) NOT NULL);
CREATE TABLE vet_specialties (vet_id BIGINT NOT NULL REFERENCES vets(id), specialty_id BIGINT NOT NULL REFERENCES specialties(id), PRIMARY KEY (vet_id, specialty_id));
